// Fetches GitHub profile + repo data with an authenticated request (5,000/hour)
// and writes a content-hashed static JSON file the deployed site reads
// same-origin, so no visitor's browser ever calls api.github.com directly
// (which is capped at 60 requests/hour per IP and gets exhausted almost
// immediately). The filename changes on every run so GitHub Pages' CDN,
// which has been observed to keep serving a fixed-name file stale well
// past its own Cache-Control max-age, can never return an old copy under
// the new name.
import { writeFile, readdir, unlink, mkdir } from 'node:fs/promises'
import { createHash } from 'node:crypto'

const username = 'jarjishSiddibapa'
const token = process.env.GITHUB_TOKEN
const headers = {
  Accept: 'application/vnd.github+json',
  ...(token ? { Authorization: `Bearer ${token}` } : {}),
}

const to = new Date()
const from = new Date(to)
from.setFullYear(from.getFullYear() - 1)

const contributionsQuery = `
  query($login: String!, $from: DateTime!, $to: DateTime!) {
    user(login: $login) {
      contributionsCollection(from: $from, to: $to) {
        contributionCalendar {
          totalContributions
          weeks {
            contributionDays {
              date
              contributionCount
            }
          }
        }
      }
    }
  }
`

const [profileRes, reposRes, contributionsRes] = await Promise.all([
  fetch(`https://api.github.com/users/${username}`, { headers }),
  fetch(`https://api.github.com/users/${username}/repos?sort=updated&per_page=100`, { headers }),
  fetch('https://api.github.com/graphql', {
    method: 'POST',
    headers: { ...headers, 'Content-Type': 'application/json' },
    body: JSON.stringify({
      query: contributionsQuery,
      variables: { login: username, from: from.toISOString(), to: to.toISOString() },
    }),
  }),
])

if (!profileRes.ok || !reposRes.ok || !contributionsRes.ok) {
  throw new Error(
    `GitHub API request failed: profile=${profileRes.status} repos=${reposRes.status} contributions=${contributionsRes.status}`,
  )
}

const profile = await profileRes.json()
const repos = await reposRes.json()
const contributionsBody = await contributionsRes.json()
if (contributionsBody.errors) {
  throw new Error(`GitHub GraphQL error: ${JSON.stringify(contributionsBody.errors)}`)
}
const calendar = contributionsBody.data.user.contributionsCollection.contributionCalendar

const output = {
  generatedAt: new Date().toISOString(),
  profile: {
    followers: profile.followers,
    public_repos: profile.public_repos,
    avatar_url: profile.avatar_url,
    bio: profile.bio,
    html_url: profile.html_url,
  },
  repos: repos.map((repo) => ({
    id: repo.id,
    name: repo.name,
    html_url: repo.html_url,
    description: repo.description,
    stargazers_count: repo.stargazers_count,
    language: repo.language,
    fork: repo.fork,
    updated_at: repo.updated_at,
  })),
  contributions: {
    totalContributions: calendar.totalContributions,
    days: calendar.weeks.flatMap((week) =>
      week.contributionDays.map((day) => ({ date: day.date, count: day.contributionCount })),
    ),
  },
}

const json = JSON.stringify(output, null, 2) + '\n'
const hash = createHash('sha1').update(json).digest('hex').slice(0, 10)
const filename = `github-stats.${hash}.json`

const publicDir = 'public'
const existing = await readdir(publicDir)
await Promise.all(
  existing
    .filter((name) => /^github-stats(\.[a-f0-9]+)?\.json$/.test(name) && name !== filename)
    .map((name) => unlink(`${publicDir}/${name}`)),
)

await writeFile(`${publicDir}/${filename}`, json)

await mkdir('src/generated', { recursive: true })
await writeFile(
  'src/generated/stats-file.ts',
  `// Auto-generated by scripts/fetch-github-stats.mjs — do not edit by hand.\nexport const STATS_FILE = '${filename}'\n`,
)

console.log(`Wrote public/${filename} (${output.repos.length} repos)`)
